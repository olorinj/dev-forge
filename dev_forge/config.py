"""Host dimensioning and configuration management for dev-forge."""

import os
from pathlib import Path
from dev_forge.banner import log_info, log_ok
from dev_forge.hardware import detect_hardware


def get_user_config_dir() -> Path:
    """Return the dedicated user profile configuration directory."""
    if os.name == "nt":
        base = os.environ.get("USERPROFILE", os.path.expanduser("~"))
    else:
        base = os.path.expanduser("~")
    return Path(base) / ".dev-forge"


def get_host_env_path() -> Path:
    """Return the absolute path to the forge-host.env file in user profile."""
    return get_user_config_dir() / "forge-host.env"


def get_config_toml_path() -> Path:
    """Return the absolute path to the config.toml file in user profile."""
    return get_user_config_dir() / "config.toml"


def generate_host_profile() -> None:
    """Evaluate host resources and generate user profile configuration."""
    hw = detect_hardware()
    config_dir = get_user_config_dir()
    config_dir.mkdir(parents=True, exist_ok=True)

    # Memory allocation tiers strictly protecting host headroom
    total_ram_gb = hw.total_ram_mb // 1024
    if total_ram_gb <= 8:
        linux_mem = 3072
        win_mem = 3584
        cpus = min(2, hw.logical_cores)
    elif total_ram_gb <= 16:
        # Tier 16GB: reserve >11GB for host desktop, browser, and IDE
        linux_mem = 4096
        win_mem = 4096
        cpus = min(2, hw.logical_cores)
    elif total_ram_gb <= 32:
        linux_mem = 8192
        win_mem = 8192
        cpus = min(4, hw.logical_cores)
    else:
        linux_mem = 12288
        win_mem = 12288
        cpus = min(8, hw.logical_cores)

    # Write forge-host.env
    env_path = get_host_env_path()
    env_content = f"""# dev-forge: Host Hardware Profile
# Auto-generated by dev-forge tune (Python Engine)
FORGE_HOST_OS="{hw.platform_name}"
FORGE_HOST_TOTAL_RAM_MB="{hw.total_ram_mb}"
FORGE_HOST_PHYSICAL_CORES="{hw.physical_cores}"
FORGE_HOST_LOGICAL_CORES="{hw.logical_cores}"
FORGE_HOST_KEYBOARD="{hw.keyboard_layout}"

# Optimal VM Dimensioning
FORGE_LINUX_MEM="{linux_mem}"
FORGE_LINUX_CPUS="{cpus}"
FORGE_WIN_MEM="{win_mem}"
FORGE_WIN_CPUS="{cpus}"
"""
    env_path.write_text(env_content, encoding="utf-8")

    # Write config.toml
    toml_path = get_config_toml_path()
    toml_content = f"""[host]
os = "{hw.platform_name}"
total_ram_mb = {hw.total_ram_mb}
logical_cores = {hw.logical_cores}
physical_cores = {hw.physical_cores}
keyboard = "{hw.keyboard_layout}"

[virtualization.linux]
memory_mb = {linux_mem}
cpus = {cpus}

[virtualization.windows]
memory_mb = {win_mem}
cpus = {cpus}
"""
    toml_path.write_text(toml_content, encoding="utf-8")

    log_ok(f"Perfil de hardware guardado en: {env_path}")
    log_info(
        f"Dimensionado: Linux={linux_mem}MB ({cpus} cpus), Windows={win_mem}MB ({cpus} cpus), Teclado={hw.keyboard_layout}"
    )


def load_host_profile() -> None:
    """Load user profile environment variables into the active process if not set."""
    env_path = get_host_env_path()
    if not env_path.is_file():
        generate_host_profile()

    try:
        content = env_path.read_text(encoding="utf-8")
        for line in content.splitlines():
            line = line.strip()
            if not line or line.startswith("#"):
                continue
            if "=" in line:
                k, v = line.split("=", 1)
                k = k.strip()
                v = v.strip().strip('"').strip("'")
                if k and k not in os.environ:
                    os.environ[k] = v
    except Exception:
        pass
